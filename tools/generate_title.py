def generate_title(topic: str, count: int = 5, style: str = "淘宝") -> str:
    style_map = {
        "淘宝": """
        1. 长度严格控制在 30 个字以内。
        2. 结构：核心品类词 + 核心卖点 + 属性词（材质/款式）+ 适用场景/人群 + 促销词。
        3. 格式：禁止使用标点符号，用空格隔开（方便搜索引擎分词）。
        4. 语气：直白、硬核、卖点优先，严禁使用小红书式的夸张口语（如“谁懂啊”、“绝绝子”）。
        5. 硬性要求：必须包含至少 3 个可以被用户搜索的关键词。
        """,
        "小红书": """
        1. 长度严格控制在 25 个字以内（太长会被截断，影响点击率）。
        2. 结构：情绪词/悬念 + 特定人群标签 + 核心卖点 + 强烈的视觉符号（Emoji）。
        3. 语气：口语化，像是闺蜜在分享好东西，强调“踩坑避雷”、“听劝”、“真香”。
        4. 技巧：善用数字列表法（如“3个技巧”、“5款好物”）、反差法（如“千万别买XX，除非...”）。
        5. 硬性要求：必须包含至少 1 个 Emoji，必须提到特定人群（如：打工人、学生党、早八人、微胖女孩）。
        """
    }
    
    # 1. 从字典里提取当前风格对应的规则，如果没匹配上，默认用淘宝
    current_rules = style_map.get(style, style_map["淘宝"])

    # 2. 将规则动态注入到提示词中
    prompt = f"""
你是一位顶级的电商爆款文案专家。
请根据以下主题，生成 {count} 个【{style}】风格的标题。

【主题】
{topic}

【当前风格的硬性规则】（必须严格遵守！）
{current_rules}

【通用输出要求】
1. 每个标题独立成行，不要序号。
2. 标题要有吸引力，能让人想点进去。
3. 突出卖点：材质、版型、场景、人群。
4. 不要写成研究报告或论文标题。
5. 只输出标题，不要加任何解释。
"""
    return prompt
